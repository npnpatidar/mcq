/**
 * One block of a question's content: plain text, an image, a table, a MathML
 * formula, or a chemical structure (SMILES). A question, option, or
 * explanation is a list of these, so rich content (a table inside a question,
 * a formula inside an option) round-trips through import, storage, and export.
 */
sealed interface ContentElement {
    /** Discriminator for the flat `{"type": ..., "content": ...}` wire format. */
    val type: String

    data class TextElement(val text: String) : ContentElement {
        override val type: String get() = "text"
    }

    data class ImageElement(val src: String) : ContentElement {
        override val type: String get() = "image"
    }

    data class TableElement(val rows: List<List<String>>) : ContentElement {
        override val type: String get() = "table"
    }

    data class MathElement(val mathml: String) : ContentElement {
        override val type: String get() = "math"
    }

    /**
     * A chemical structure drawn from a SMILES string by the bundled offline
     * SmilesDrawer asset. [smiles] is the required source (e.g. "c1ccccc1");
     * the rest are optional. [diagram] is a base64 PNG data URI used by
     * exports — it is never generated by the AI schema, which only supplies
     * SMILES, formula, caption and spoken.
     */
    data class ChemElement(
        val smiles: String,
        val formula: String = "",
        val caption: String = "",
        val spoken: String = "",
        val diagram: String = ""
    ) : ContentElement {
        override val type: String get() = "chem"
    }
}

/**
 * Serializes a [ContentElement] as the flat `{"type": ..., "content": ...}`
 * shape used by the structured import format and the database columns (the
 * default polymorphic shape would nest each subclass's fields instead).
 */
object ContentElementJson : KSerializer<ContentElement> {

    override val descriptor: SerialDescriptor = buildClassSerialDescriptor("ContentElement") {
        element("type", String.serializer().descriptor)
        element("content", JsonElement.serializer().descriptor)
    }

    override fun serialize(encoder: Encoder, value: ContentElement) {
        val content = when (value) {
            is ContentElement.TextElement -> JsonPrimitive(value.text)
            is ContentElement.ImageElement -> JsonPrimitive(value.src)
            is ContentElement.TableElement -> buildJsonArray {
                value.rows.forEach { row ->
                    add(buildJsonArray { row.forEach { cell -> add(JsonPrimitive(cell)) } })
                }
            }
            is ContentElement.MathElement -> JsonPrimitive(value.mathml)
            // Chemistry carries an object, not a scalar: all five keys are
            // written (empty strings allowed) so the wire shape is stable.
            is ContentElement.ChemElement -> buildJsonObject {
                put("smiles", JsonPrimitive(value.smiles))
                put("formula", JsonPrimitive(value.formula))
                put("caption", JsonPrimitive(value.caption))
                put("spoken", JsonPrimitive(value.spoken))
                put("diagram", JsonPrimitive(value.diagram))
            }
        }
        encoder.encodeSerializableValue(JsonElement.serializer(), buildJsonObject {
            put("type", JsonPrimitive(value.type))
            put("content", content)
        })
    }

    override fun deserialize(decoder: Decoder): ContentElement {
        val obj = decoder.decodeSerializableValue(JsonElement.serializer()).jsonObject
        return decodeContentElement(obj)
            ?: throw SerializationException("Unknown or malformed content element")
    }
}

/**
 * Decodes one `{type, content}` block. Null means "skip this block": the list
 * reader drops it so an unknown or malformed element cannot poison the whole
 * list (which used to turn every good block into one plain-text fallback).
 */
private fun decodeContentElement(obj: JsonObject): ContentElement? {
    val type = obj["type"]?.stringOrNull() ?: return null
    val content = obj["content"] ?: return null
    return when (type) {
        "text" -> ContentElement.TextElement(content.stringOrNull() ?: return null)
        "image" -> ContentElement.ImageElement(content.stringOrNull() ?: return null)
        "math" -> ContentElement.MathElement(content.stringOrNull() ?: return null)
        "table" -> {
            val rows = content as? JsonArray ?: return null
            val decoded = mutableListOf<List<String>>()
            for (row in rows) {
                val cells = row as? JsonArray ?: return null
                val decodedRow = mutableListOf<String>()
                for (cell in cells) decodedRow += cell.stringOrNull() ?: return null
                decoded += decodedRow
            }
            ContentElement.TableElement(decoded)
        }
        "chem" -> {
            val c = content as? JsonObject ?: return null
            fun field(key: String): String = c[key]?.stringOrNull() ?: ""
            // Same rule as LegacyParser: a chem block with no SMILES cannot be
            // drawn, so drop just this block rather than store an element the
            // renderer has nothing to render.
            val smiles = field("smiles").trim()
            if (smiles.isEmpty()) return null
            ContentElement.ChemElement(
                smiles = smiles,
                formula = field("formula"),
                caption = field("caption"),
                spoken = field("spoken"),
                diagram = field("diagram")
            )
        }
        else -> null
    }
}

private fun JsonElement.stringOrNull(): String? = (this as? JsonPrimitive)?.contentOrNull

/** [ContentElementJson] for a list, so DTO properties can use `@Serializable(with = ...)`. */
object ContentElementListJson : KSerializer<List<ContentElement>> {

    private val delegate = ListSerializer(ContentElementJson)

    override val descriptor: SerialDescriptor = delegate.descriptor

    override fun serialize(encoder: Encoder, value: List<ContentElement>) =
        delegate.serialize(encoder, value)

    override fun deserialize(decoder: Decoder): List<ContentElement> {
        // Decode element by element instead of through ListSerializer: one
        // unknown/malformed block used to throw out of the whole list and
        // turned every good block into a single TextElement of raw JSON.
        // Dropping just the bad block matches LegacyParser's tolerance.
        val array = decoder.decodeSerializableValue(JsonElement.serializer()).jsonArray
        return array.mapNotNull { element ->
            (element as? JsonObject)?.let(::decodeContentElement)
        }
    }
}

/** Concatenated text of the [ContentElement.TextElement]s — the backward-compat
 *  `text` used by scoring, stats, and search. */
val List<ContentElement>.textContent: String
    get() = filterIsInstance<ContentElement.TextElement>().joinToString("") { it.text }

/**
 * True when these blocks carry anything visible (a blank text run is not).
 *
 * [textContent] cannot answer this: an explanation made only of a picture, a
 * table or a formula flattens to "" and used to be treated as absent, so it
 * never rendered. Kept exhaustive so a future element kind has to decide.
 */
val List<ContentElement>.hasVisibleContent: Boolean
    get() = any { el ->
        when (el) {
            is ContentElement.TextElement -> el.text.isNotBlank()
            is ContentElement.ImageElement -> el.src.isNotBlank()
            is ContentElement.TableElement -> el.rows.any { row -> row.any { it.isNotBlank() } }
            is ContentElement.MathElement -> el.mathml.isNotBlank()
            is ContentElement.ChemElement ->
                el.smiles.isNotBlank() || el.formula.isNotBlank() || el.caption.isNotBlank() ||
                    el.spoken.isNotBlank() || el.diagram.isNotBlank()
        }
    }

/**
 * Everything a reader can actually see, flattened for searching.
 *
 * [textContent] is the wrong basis for search: it drops tables and formulas
 * entirely, so a question whose only mention of a name sits in a table cell or
 * inside a formula could not be found at all. It also keeps inline markup, so
 * searching "strong" used to match questions merely containing a `<strong>`
 * tag. Deliberately separate from [textContent], which duplicate detection and
 * the explanation comparison both rely on.
 *
 * A picture contributes nothing: there is no text to match.
 */
val List<ContentElement>.searchableText: String
    get() = mapNotNull { element ->
        when (element) {
            is ContentElement.TextElement -> stripMarkup(element.text)
            is ContentElement.TableElement ->
                element.rows.flatten().joinToString(" ") { stripMarkup(it) }
            // No space between tokens, so a formula reads the way it is typed:
            // stripping tags with a space would give "v = u + a t", which a
            // search for "v=u+at" would miss.
            is ContentElement.MathElement -> element.mathml.replace(TAG_OR_ENTITY, "")
            is ContentElement.ImageElement -> null
            // SMILES, formula and caption are the human/machine-readable handles
            // a learner might search for. Spoken is an accessibility label and
            // diagram is base64 image data, so neither is text to search.
            is ContentElement.ChemElement -> stripMarkup(
                listOf(element.smiles, element.formula, element.caption)
                    .filter { it.isNotBlank() }
                    .joinToString(" ")
            ).takeIf { it.isNotBlank() }
        }
    }.joinToString(" ").replace(WHITESPACE_RUNS, " ").trim()

/**
 * The one-line preview a list row shows for a question: the visible text with
 * markup gone — the same string search matched on and the browse list shows
 * from its stored `searchText` column.
 *
 * [Question.text] is the wrong basis: it concatenates the text elements as
 * stored, so an imported stem keeps its inline markup and a row rendered
 * "&lt;b&gt;Bold&lt;/b&gt; answer" instead of "Bold answer".
 */
val Question.previewText: String get() = elements.searchableText

private val WHITESPACE_RUNS = Regex("\\s+")

/**
 * The flattened text a passage is searched by: its title plus its body, so a
 * member question can be found through its shared context. Mirrors the
 * `title + body` string the in-memory search builds per passage.
 */
fun passageSearchText(title: String, elements: List<ContentElement>): String =
    (title + " " + elements.searchableText).trim()

/** Drops tags and entities, leaving the text between them. */
private fun stripMarkup(raw: String): String = if ('<' in raw || '&' in raw) {
    TAG_OR_ENTITY.replace(raw, " ")
} else {
    raw
}

private val TAG_OR_ENTITY = Regex("<[^>]*>|&[a-zA-Z#0-9]+;")

/** Serializes elements to the flat JSON stored in the text/explanation columns. */
fun List<ContentElement>.toContentJson(json: Json): String =
    json.encodeToString(ContentElementListJson, this)

/**
 * Parses a column value back into elements. Legacy rows hold plain text, not
 * JSON, so anything that is not a JSON array becomes a single TextElement.
 */
fun String.parseContentElements(json: Json): List<ContentElement> {
    val trimmed = trim()
    if (!trimmed.startsWith("[")) return listOf(ContentElement.TextElement(this))
    return try {
        json.decodeFromString(ContentElementListJson, trimmed)
    } catch (_: Exception) {
        listOf(ContentElement.TextElement(this))
    }
}

data class QuestionOption(
    val id: String,
    val elements: List<ContentElement>,
    val image: String? = null
) {
    /** Backward-compat: the concatenated text. */
    val text: String get() = elements.textContent

    /** Backward-compat constructor: plain text becomes one TextElement. */
    constructor(id: String, text: String, image: String? = null) : this(
        id,
        listOf(ContentElement.TextElement(text)),
        image
    )
}

enum class Difficulty(
    /** Stable storage/import token. Never localised: it is written to DTOs and
     *  compared with `fromLabel`, so changing it would break imports and FKs. */
    val label: String,
    /** Display copy, resolved with `stringResource` at the call site. */
    @StringRes val labelRes: Int
) {
    EASY("Easy", com.mcqapp.R.string.r2_editor_difficulty_easy),
    MEDIUM("Medium", com.mcqapp.R.string.r2_editor_difficulty_medium),
    HARD("Hard", com.mcqapp.R.string.r2_editor_difficulty_hard);

    companion object {
        fun fromLabel(label: String): Difficulty =
            entries.firstOrNull { it.label.equals(label, ignoreCase = true) } ?: MEDIUM
    }
}

data class Question(
    val id: String,
    val categoryId: String,
    val elements: List<ContentElement>,
    val image: String? = null,
    val options: List<QuestionOption>,
    val correctOptionIds: Set<String>,
    val explanationElements: List<ContentElement> = emptyList(),
    val explanationImage: String? = null,
    val difficulty: Difficulty = Difficulty.MEDIUM,
    val marks: Double = 1.0,
    val tags: List<String> = emptyList(),
    /** The passage (shared reading context) this question belongs to, if any. */
    val passageId: String? = null
) {
    val isMultiCorrect: Boolean get() = correctOptionIds.size > 1

    /** Backward-compat: the concatenated text, for scoring/stats/search. */
    val text: String get() = elements.textContent

    /** Backward-compat: the concatenated explanation text. */
    val explanation: String get() = explanationElements.textContent

    /** Backward-compat constructor: plain text becomes one TextElement. */
    constructor(
        id: String,
        categoryId: String,
        text: String,
        image: String? = null,
        options: List<QuestionOption>,
        correctOptionIds: Set<String>,
        explanation: String = "",
        explanationImage: String? = null,
        difficulty: Difficulty = Difficulty.MEDIUM,
        marks: Double = 1.0,
        tags: List<String> = emptyList()
    ) : this(
        id,
        categoryId,
        listOf(ContentElement.TextElement(text)),
        image,
        options,
        correctOptionIds,
        listOf(ContentElement.TextElement(explanation)),
        explanationImage,
        difficulty,
        marks,
        tags,
        passageId = null
    )
}

/**
 * A card with no options is a flashcard: the stem is the front and the
 * explanation is the back. Derived, never stored — options present means a
 * multiple-choice card.
 */
val Question.isFlashcard: Boolean get() = options.isEmpty()

/**
 * A reading passage: shared context for a group of questions.
 *
 * Members live as ordinary [Question]s pointing at this id through
 * `passageId`; the passage itself only carries the context (title, body,
 * image) and its category, which gives it a home in the paper structure.
 *
 * Scheduling, bookmarks, attempts and stats stay per question — the passage
 * is not schedulable content, only what surrounds the question on screen.
 */
data class Passage(
    val id: String,
    val categoryId: String,
    val title: String,
    val elements: List<ContentElement> = emptyList(),
    val image: String? = null,
    val sortOrder: Int = 0,
    /** member count filled in by the repository read, 0 when not requested. */
    val memberCount: Int = 0
) {
    /** Backward-compat concatenated body text. */
    val text: String get() = elements.textContent
}

data class CategoryNode(
    val id: String,
    val paperId: String,
    val title: String,
    val parentId: String?,
    val children: List<CategoryNode> = emptyList(),
    val questionCount: Int = 0
) {
    val totalQuestionCount: Int get() = questionCount + children.sumOf { it.totalQuestionCount }
}

data class Paper(
    val id: String,
    val title: String,
    val description: String = "",
    val durationMinutes: Int = 0,
    val negativeMarking: Double = 0.0,
    val categories: List<CategoryNode> = emptyList()
) {
    val totalQuestions: Int get() = categories.sumOf { it.totalQuestionCount }
}

data class Attempt(
    val id: Long,
    val paperId: String,
    val title: String,
    val totalQuestions: Int,
    val correctCount: Int,
    val wrongCount: Int,
    val skippedCount: Int,
    val score: Double,
    val maxScore: Double,
    val durationSeconds: Long,
    val finishedAt: Long,
    /**
     * The bounded-Test metadata (section 12.1). Every default is the legacy
     * value, so a pre-v21 row reads as "no type, no requested count, sampling
     * version 1" and is never comparable.
     */
    val testType: String? = null,
    val requestedCount: Int = 0,
    val scopeCategoryIds: String = "",
    val scopeKey: String = "",
    val samplingVersion: Int = 1,
    val seed: Long = 0,
    val exclusionMode: String = "NONE",
    val targetTopicIds: String = "",
    val compositionJson: String = "",
    /** The custom type's choice: the tag or difficulty a Tag/Authored run used. */
    val variant: String? = null,
    /**
     * The penalty rate the attempt applied. Null for pre-v24 rows and for
     * imports from older files; [TestReportBuilder.markingOf] then falls back
     * to the historic reconstruction.
     */
    val negativeMarking: Double? = null
) {
    val percentage: Double get() = if (maxScore > 0) score / maxScore * 100.0 else 0.0

    /**
     * `correct / (correct + wrong)`: how well the learner did on what they
     * attempted. Distinct from [percentage], which scores the exam (skips are
     * in its denominator, negative marking applies to wrong answers).
     */
    val accuracyOnAnswered: Double
        get() = if (correctCount + wrongCount > 0) {
            correctCount.toDouble() / (correctCount + wrongCount)
        } else {
            0.0
        }

    /**
     * `correct / totalQuestions`: the proportion the report's margin describes.
     * A skipped or ungraded question is in the denominator, exactly as it is
     * in `ScoreSummary.accuracyAsked`.
     */
    val accuracyOnShown: Double
        get() = if (totalQuestions > 0) correctCount.toDouble() / totalQuestions else 0.0
}

/**
 * The bounded-Test metadata an attempt persists (section 12.1), passed to the
 * save path as one value. Defaults are the legacy values: a caller that does
 * not supply metadata writes a legacy attempt, which is never comparable and
 * never moves the representative counters.
 */
data class AttemptMetadata(
    val testType: String? = null,
    val requestedCount: Int = 0,
    val scopeCategoryIds: String = "",
    val scopeKey: String = "",
    val samplingVersion: Int = 1,
    val seed: Long = 0,
    val exclusionMode: String = "NONE",
    val targetTopicIds: String = "",
    val compositionJson: String = "",
    /** The custom type's choice: the tag or difficulty a Tag/Authored run used. */
    val variant: String? = null
)

/**
 * A result row plus its position in the **unfiltered** attempt order. Browse
 * carries this so a filtered review still shows each question's real number
 * (`index + 1`) without holding the whole attempt in memory.
 */
data class NumberedResult(
    val index: Int,
    val result: QuestionResult
)

data class QuestionResult(
    val attemptId: Long = 0,
    val dwellSeconds: Long = 0,
    val questionId: String,
    val categoryTitle: String,
    val elements: List<ContentElement>,
    val options: List<QuestionOption>,
    val correctOptionIds: Set<String>,
    val selectedOptionIds: Set<String>,
    val isCorrect: Boolean,
    val explanationElements: List<ContentElement> = emptyList(),
    val explanationImage: String? = null,
    /**
     * The passage this question belonged to, resolved live by question id when
     * the result page is read. It is not stored on the result row (no schema
     * change): a passage edited after the attempt should show the context the
     * learner would see today, above the stem.
     */
    val passage: Passage? = null
) {
    /** Backward-compat: the concatenated text. */
    val text: String get() = elements.textContent

    /** Backward-compat: the concatenated explanation text. */
    val explanation: String get() = explanationElements.textContent

    /** Backward-compat constructor: plain text becomes one TextElement. */
    constructor(
        attemptId: Long = 0,
        dwellSeconds: Long = 0,
        questionId: String,
        categoryTitle: String,
        text: String,
        options: List<QuestionOption>,
        correctOptionIds: Set<String>,
        selectedOptionIds: Set<String>,
        isCorrect: Boolean,
        explanation: String = "",
        explanationImage: String? = null
    ) : this(
        attemptId,
        dwellSeconds,
        questionId,
        categoryTitle,
        listOf(ContentElement.TextElement(text)),
        options,
        correctOptionIds,
        selectedOptionIds,
        isCorrect,
        listOf(ContentElement.TextElement(explanation)),
        explanationImage
    )
}

/**
 * A bookmarked question together with the paper it came from.
 *
 * The editor route needs the paper id: without it the editor loads no
 * categories and silently hides the category picker.
 */
data class BookmarkedQuestion(val paperId: String, val question: Question)
