package com.mcqapp

import android.content.Context
import android.database.sqlite.SQLiteDatabase
import androidx.room.Room
import androidx.test.core.app.ApplicationProvider
import com.mcqapp.data.local.AppDatabase
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

/**
 * 29 -> 30 adds the two suspend columns and keeps every existing card row.
 *
 * `MigrationTestHelper` lives in `androidx.room:room-testing`, which this
 * project deliberately does not depend on (no new dependencies for this
 * feature). Instead the test builds a real v29 file from the current schema's
 * own `sqlite_master` SQL with just those two columns removed, stamps it
 * `user_version = 29`, seeds a card, and opens it through the production
 * [AppDatabase.builder] — so the actual registered migration runs and Room's
 * post-migration schema validation still guards the result.
 *
 * Robolectric + real SQLite: CI (x86_64) is authoritative.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class SuspendMigrationTest {

    @get:Rule
    val watchdog = HangWatchdogRule(seconds = 120)

    private val dbName = "suspend-migration-v29-test.db"

    private fun file(context: Context) = context.getDatabasePath(dbName)

    @After
    fun tearDown() {
        file(ApplicationProvider.getApplicationContext()).delete()
    }

    /**
     * Captures the complete CREATE SQL of a fresh v30 database, then rebuilds
     * the same file as v29. Autogenerated `sqlite_autoindex_*` entries have no
     * SQL and are skipped; Room recreates them with their tables. The master
     * table carries v30's identity hash, so it is left out too — Room writes a
     * fresh one when it opens the migrated file.
     */
    private fun createV29File(context: Context) {
        val path = file(context)
        path.parentFile?.mkdirs()
        path.delete()

        val bootstrap = Room.databaseBuilder(context, AppDatabase::class.java, dbName).build()
        val statements = mutableListOf<Pair<String, String>>()
        bootstrap.openHelper.readableDatabase.query(
            "SELECT name, sql FROM sqlite_master " +
                "WHERE sql IS NOT NULL AND type IN ('table','index') " +
                // 'table' sorts after 'index', so DESC creates tables first;
                // sqlite_master otherwise returns creation order, which is
                // enough here but is not a contract to lean on.
                "ORDER BY type DESC, name"
        ).use { c ->
            while (c.moveToNext()) {
                val name = c.getString(0)
                if (name == "room_master_table" || name == "android_metadata") continue
                statements += name to c.getString(1)
            }
        }
        bootstrap.close()
        path.delete()

        val raw = SQLiteDatabase.openOrCreateDatabase(path, null)
        try {
            statements.forEach { (_, sql) ->
                val v29 = sql
                    .replace("`suspended` INTEGER NOT NULL DEFAULT 0, ", "")
                    .replace("`buriedUntil` INTEGER, ", "")
                raw.execSQL(v29)
            }
            raw.execSQL("PRAGMA user_version = 29")
            raw.execSQL(
                "INSERT INTO papers (id, title, description, durationMinutes, " +
                    "negativeMarking, createdAt, sortOrder) " +
                    "VALUES ('p1', 'Paper', '', 0, 0.0, 1000, 0)"
            )
            raw.execSQL(
                "INSERT INTO card_state (paperId, questionId, ease, intervalDays, dueAt, " +
                    "reps, lapses, leech, lastReviewedAt, contentHash, difficulty, " +
                    "stability, stabilityFast, cardState, reviewCount) " +
                    "VALUES ('p1', 'q1', 2.31, 9, 123456, 7, 1, 0, 111, 'hash', 5.5, 21.0, " +
                    "18.0, 'REVIEW', 7)"
            )
        } finally {
            raw.close()
        }
    }

    @Test
    fun migrationAddsBothColumnsAndKeepsTheCardRow() {
        val context = ApplicationProvider.getApplicationContext<Context>()
        createV29File(context)

        val db = AppDatabase.builder(context, dbName).build()
        try {
            assertEquals(30, db.openHelper.readableDatabase.version)
            val card = kotlinx.coroutines.runBlocking { db.cardStateDao().get("p1", "q1") }
            assertNotNull("the existing card survives the migration", card)
            card!!
            assertFalse("an upgraded card is ordinary, not suspended", card.suspended)
            assertNull("an upgraded card is not buried", card.buriedUntil)
            // Nothing about the schedule the learner already earned moved.
            assertEquals(2.31, card.ease, 0.0)
            assertEquals(9, card.intervalDays)
            assertEquals(123456L, card.dueAt)
            assertEquals(7, card.reps)
            assertEquals(1, card.lapses)
            assertEquals("hash", card.contentHash)
            assertEquals(5.5, card.difficulty, 0.0)
            assertEquals(21.0, card.stability, 0.0)
            assertEquals(18.0, card.stabilityFast, 0.0)
            assertEquals(7, card.reviewCount)
            assertTrue(
                "the new columns are usable by the DAO immediately",
                runBlockingSelect(db)
            )
        } finally {
            db.close()
        }
    }

    /** Exercises a v30 write against the migrated file, not just a read. */
    private fun runBlockingSelect(db: AppDatabase): Boolean = kotlinx.coroutines.runBlocking {
        db.cardStateDao().setSuspended("p1", "q1")
        db.cardStateDao().get("p1", "q1")!!.suspended
    }
}
